namespace SdlSharp.Input;

/// <summary>
/// Mouse button identifiers.
/// </summary>
public enum MouseButton : byte
{
    /// <summary>
    /// The left mouse button.
    /// </summary>
    Left = 1,

    /// <summary>
    /// The middle mouse button.
    /// </summary>
    Middle = 2,

    /// <summary>
    /// The right mouse button.
    /// </summary>
    Right = 3,

    /// <summary>
    /// The first extra mouse button (side button 1).
    /// </summary>
    X1 = 4,

    /// <summary>
    /// The second extra mouse button (side button 2).
    /// </summary>
    X2 = 5,
}
