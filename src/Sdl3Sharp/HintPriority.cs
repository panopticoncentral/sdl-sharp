namespace Sdl3Sharp;

/// <summary>
/// An enumeration of hint priorities.
/// </summary>
public enum HintPriority
{
    /// <summary>
    /// Low priority, used for default values.
    /// </summary>
    Default,

    /// <summary>
    /// Medium priority.
    /// </summary>
    Normal,

    /// <summary>
    /// High priority.
    /// </summary>
    Override
}
