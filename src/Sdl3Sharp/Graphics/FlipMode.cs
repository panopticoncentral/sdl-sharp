namespace Sdl3Sharp.Graphics;

/// <summary>
/// The flip mode for surface operations.
/// </summary>
public enum FlipMode
{
    /// <summary>Do not flip.</summary>
    None = 0,
    /// <summary>Flip horizontally.</summary>
    Horizontal = 1,
    /// <summary>Flip vertically.</summary>
    Vertical = 2
}
