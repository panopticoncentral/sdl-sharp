namespace Sdl3Sharp;

/// <summary>
/// Specifies the different color elements in a message box color scheme.
/// </summary>
public enum MessageBoxColorType
{
    /// <summary>
    /// Background color of the message box.
    /// </summary>
    Background,

    /// <summary>
    /// Text color.
    /// </summary>
    Text,

    /// <summary>
    /// Button border color.
    /// </summary>
    ButtonBorder,

    /// <summary>
    /// Button background color.
    /// </summary>
    ButtonBackground,

    /// <summary>
    /// Selected button color.
    /// </summary>
    ButtonSelected
}
